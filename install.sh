#!/usr/bin/env bash
# ADM TOOLS — установка и обновление магазина на сервере (Ubuntu 22.04 / 24.04)
# Запуск:  bash install.sh        Повторный запуск = обновление (данные сохраняются)
set -euo pipefail
APP=/opt/adm-tools; DATA=/var/lib/adm-tools; ENVF=/etc/adm-tools.env
say(){ printf '\n\033[1;36m▶ %s\033[0m\n' "$*"; }
die(){ printf '\n\033[1;31m✖ %s\033[0m\n' "$*"; exit 1; }
[ "$(id -u)" = 0 ] || die "Запустите от имени root"
[ -f "$0" ] || die "Скачайте файл и запустите его так: bash install.sh"

say "1/6 Устанавливаю Node.js и веб-сервер Caddy (2–4 минуты)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y -qq
apt-get install -y -qq nodejs caddy curl ca-certificates >/dev/null
NODE_MAJOR=$(node -p 'process.versions.node.split(".")[0]')
[ "$NODE_MAJOR" -ge 18 ] || die "Нужен Node.js 18+, установлен $(node -v). Выберите при создании сервера Ubuntu 24.04"

say "2/6 Распаковываю магазин"
id admshop >/dev/null 2>&1 || useradd --system --user-group --no-create-home --home-dir "$DATA" --shell /usr/sbin/nologin admshop
mkdir -p "$APP" "$DATA"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xz -C "$APP"
chown -R root:root "$APP"; chmod -R a+rX "$APP"
chown -R admshop:admshop "$DATA"; chmod 750 "$DATA"

say "3/6 Настройки"
[ -f "$ENVF" ] && . "$ENVF"
if [ -z "${BOT_TOKEN:-}" ]; then
  while true; do
    read -rp "Вставьте токен бота из @BotFather и нажмите Enter: " BOT_TOKEN </dev/tty
    BOT_TOKEN=$(echo "$BOT_TOKEN" | tr -d '[:space:]')
    [[ "$BOT_TOKEN" =~ ^[0-9]+:[A-Za-z0-9_-]{30,}$ ]] && break
    echo "Не похоже на токен (вид: 1234567890:AAH...). Попробуйте ещё раз."
  done
  OK=$(curl -s --max-time 8 "https://api.telegram.org/bot${BOT_TOKEN}/getMe" | grep -o '"ok":true' || true)
  [ -n "$OK" ] || echo "⚠️  Не удалось проверить токен через Telegram (нет доступа или токен неверный). Продолжаю."
fi
if [ -z "${ADMIN_ID:-}" ]; then
  read -rp "Ваш Telegram ID [Enter = 8753317016]: " ADMIN_ID </dev/tty
  ADMIN_ID=${ADMIN_ID:-8753317016}
fi
if [ -z "${DOMAIN:-}" ]; then
  IP=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1);exit}}')
  if [ -z "$IP" ] || [[ "$IP" =~ ^(10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.) ]]; then
    IP=$(curl -4 -s --max-time 5 https://ifconfig.me || curl -4 -s --max-time 5 https://api.ipify.org || true)
  fi
  [ -n "$IP" ] || die "Не удалось узнать IP сервера"
  FREE="${IP//./-}.sslip.io"
  read -rp "Свой домен (просто Enter — бесплатный адрес $FREE): " DOMAIN </dev/tty
  DOMAIN=${DOMAIN:-$FREE}
fi
umask 077
cat > "$ENVF" <<CFG
BOT_TOKEN=$BOT_TOKEN
ADMIN_ID=$ADMIN_ID
DOMAIN=$DOMAIN
PUBLIC_URL=https://$DOMAIN
PORT=3000
DATA_DIR=$DATA
CFG
umask 022

say "4/6 Запускаю магазин"
cat > /etc/systemd/system/adm-tools.service <<UNIT
[Unit]
Description=ADM TOOLS shop
After=network-online.target
Wants=network-online.target

[Service]
User=admshop
WorkingDirectory=$APP
EnvironmentFile=$ENVF
ExecStart=/usr/bin/node $APP/server.js
Restart=always
RestartSec=3
NoNewPrivileges=true

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable adm-tools >/dev/null 2>&1
systemctl restart adm-tools

say "5/6 Включаю HTTPS для $DOMAIN"
cat > /etc/caddy/Caddyfile <<CADDY
$DOMAIN {
	encode gzip
	reverse_proxy 127.0.0.1:3000
}
CADDY
if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  ufw allow OpenSSH >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null
fi
systemctl enable caddy >/dev/null 2>&1
systemctl restart caddy

say "6/6 Проверяю"
for i in $(seq 1 15); do curl -fs http://127.0.0.1:3000/health >/dev/null && break; sleep 1; done
curl -fs http://127.0.0.1:3000/health >/dev/null || { journalctl -u adm-tools -n 30 --no-pager; die "Магазин не запустился — пришлите текст выше"; }
HTTPS_OK=""
for i in $(seq 1 40); do curl -fs --max-time 5 "https://$DOMAIN/health" >/dev/null && { HTTPS_OK=1; break; }; sleep 3; done

echo
if [ -n "$HTTPS_OK" ]; then
  printf '\033[1;32m✅ Готово! Магазин работает:  https://%s\033[0m\n' "$DOMAIN"
  echo "Бот получил кнопку «🛍 Магазин» с новым адресом, а вам пришло сообщение «Сервер магазина запущен»."
else
  printf '\033[1;33m⚠️  Магазин запущен, но HTTPS для %s ещё не готов.\033[0m\n' "$DOMAIN"
  echo "Подождите 5 минут и откройте https://$DOMAIN в браузере. Если не открылось — пришлите вывод команды:"
  echo "  journalctl -u caddy -n 40 --no-pager"
fi
echo
echo "Полезные команды:  systemctl status adm-tools   |   journalctl -u adm-tools -f"
exit 0
